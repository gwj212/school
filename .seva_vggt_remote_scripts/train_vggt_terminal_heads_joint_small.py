#!/usr/bin/env python3
"""Alternating phase-B pilot: tune only VGGT-G terminal Gaussian heads.

Inputs are cached views generated by the phase-A MVGenMaster 3D adapter. Targets
are the paired real views at the same camera slots. All VGGT backbone, camera,
depth and feature modules stay frozen.
"""

from __future__ import annotations

import argparse
import json
import math
import random
import sys
import time
from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F


TRAIN = ["cup_46_2479_7421", "laptop_386_46021_91916", "plant_529_76885_148624", "bicycle_404_53644_104645"]
VAL = ["ball_394_48737_96400", "apple_484_69426_135397"]


def load_pair(scene, manifests, generated, load_images):
    manifest = json.loads((manifests / f"{scene}.json").read_text())
    gt_paths = [v["image"] for v in manifest["views"]]
    input_paths = [gt_paths[0]] + [str(generated / scene / "images" / f"view_{i:02d}_generated.png") for i in range(1, 8)]
    return load_images(input_paths, mode="pad"), load_images(gt_paths, mode="pad")


def pred_scene(pred):
    return {k: v[0].reshape(-1, v.shape[-1]).float() for k, v in pred["gaussians"].items()
            if torch.is_tensor(v) and v.ndim >= 4}


def render_loss(pred, gt, slots, pose_fn, render_fn, ssim_fn, size):
    extr, intr = pose_fn(pred["pose_enc"].float(), (518, 518))
    extr = extr[0].float(); intr = intr[0].float() * (size / 518.0)
    intr[:, 2, 2] = 1.0
    gs = pred_scene(pred)
    losses, metrics = [], []
    for slot in slots:
        target = F.interpolate(gt[slot:slot+1].float(), (size, size), mode="bilinear", align_corners=False, antialias=True)[0]
        render = render_fn(gs["xyz"], gs["rotation"], gs["scale"], gs["opacity"], gs["color"],
                           extr[slot], intr[slot], size, size)
        l1 = F.l1_loss(render, target)
        dssim = 1.0 - ssim_fn(render[None], target[None])
        loss = 0.8*l1 + 0.2*dssim
        losses.append(loss)
        with torch.no_grad():
            mse = F.mse_loss(render, target).item()
            metrics.append({"slot": slot, "psnr": -10*math.log10(max(mse, 1e-10)),
                            "ssim": float((1.0-dssim).item()), "l1": float(l1.item())})
    return torch.stack(losses).mean(), metrics


def evaluate(model, cached, device, dtype, pose_fn, render_fn, ssim_fn, size):
    rows = []
    model.eval()
    with torch.inference_mode():
        for scene, inp, gt in cached:
            with torch.autocast("cuda", dtype=dtype): pred = model(inp[None].to(device))
            _, values = render_loss(pred, gt.to(device), [1, 3, 5, 7], pose_fn, render_fn, ssim_fn, size)
            for item in values: rows.append({"scene": scene, **item})
            del pred; torch.cuda.empty_cache()
    return {"rows": rows, "mean_psnr": float(np.mean([r["psnr"] for r in rows])),
            "mean_ssim": float(np.mean([r["ssim"] for r in rows])),
            "mean_l1": float(np.mean([r["l1"] for r in rows]))}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifests", type=Path, default=Path("/root/seva_vggt/config/joint_small_train"))
    ap.add_argument("--generated", type=Path, default=Path("/root/seva_vggt/outputs/joint_finetune_small/adapted_mvgen_trainval6"))
    ap.add_argument("--output", type=Path, required=True)
    ap.add_argument("--steps", type=int, default=24)
    ap.add_argument("--lr", type=float, default=5e-5)
    ap.add_argument("--render-size", type=int, default=256)
    ap.add_argument("--seed", type=int, default=23)
    args = ap.parse_args(); args.output.mkdir(parents=True, exist_ok=True)
    random.seed(args.seed); np.random.seed(args.seed); torch.manual_seed(args.seed)
    sys.path[:0] = ["/root/vggt", "/root/seva_vggt/bridge"]
    import run_pipeline as rp
    from vggt.models.vggt import VGGT
    from vggt.utils.load_fn import load_and_preprocess_images
    from vggt.utils.pose_enc import pose_encoding_to_extri_intri
    from vggt.utils.gs_optimizer import render_gaussians, ssim

    device = torch.device("cuda:0")
    dtype = torch.bfloat16 if torch.cuda.get_device_capability(device)[0] >= 8 else torch.float16
    started = time.perf_counter()
    cached = [(s, *load_pair(s, args.manifests, args.generated, load_and_preprocess_images)) for s in TRAIN+VAL]
    model = VGGT.from_pretrained(str(rp.DEFAULT_VGGT_MODEL), enable_gaussian=True)
    if hasattr(model.gaussian_head, "enable_color_head_after_init"): model.gaussian_head.enable_color_head_after_init()
    checkpoint = rp.load_reconstruction_checkpoint(model, Path("/root/vggt/ckpts/ckpt.pth"))
    model.point_head = None; model.track_head = None; model.requires_grad_(False)
    prefixes = ("xyz_head.", "rot_head.", "scale_head.", "opacity_head.", "color_head.")
    trainable_names = []
    for name, param in model.gaussian_head.named_parameters():
        if name.startswith(prefixes): param.requires_grad_(True); trainable_names.append(name)
    model.to(device).eval()
    trainable = [p for p in model.parameters() if p.requires_grad]
    trainable_count = sum(p.numel() for p in trainable)
    initial = {n: p.detach().clone() for n,p in model.gaussian_head.named_parameters() if p.requires_grad}
    train_cache = cached[:len(TRAIN)]; val_cache = cached[len(TRAIN):]
    before = evaluate(model, val_cache, device, dtype, pose_encoding_to_extri_intri, render_gaussians, ssim, args.render_size)
    optimizer = torch.optim.AdamW(trainable, lr=args.lr, weight_decay=0.01)
    trace = []; torch.cuda.reset_peak_memory_stats(device)
    for step in range(args.steps):
        scene, inp, gt = train_cache[step % len(train_cache)]
        optimizer.zero_grad(set_to_none=True)
        with torch.autocast("cuda", dtype=dtype): pred = model(inp[None].to(device))
        generated_slot = 1 + ((step * 3 + step // len(train_cache)) % 7)
        loss_render, step_metrics = render_loss(pred, gt.to(device), [0, generated_slot],
                                                pose_encoding_to_extri_intri, render_gaussians, ssim, args.render_size)
        reg = torch.stack([(p-initial[n]).float().pow(2).mean()
                           for n,p in model.gaussian_head.named_parameters() if p.requires_grad]).mean()
        loss = loss_render + 0.01*reg
        loss.backward(); grad = float(torch.nn.utils.clip_grad_norm_(trainable, 1.0).item()); optimizer.step()
        row = {"step": step+1, "scene": scene, "generated_slot": generated_slot,
               "loss": float(loss.item()), "render_loss": float(loss_render.item()), "reg": float(reg.item()),
               "grad_norm": grad, "slot_metrics": step_metrics}
        trace.append(row); print(json.dumps(row), flush=True)
        del pred, loss, loss_render; torch.cuda.empty_cache()
    after = evaluate(model, val_cache, device, dtype, pose_encoding_to_extri_intri, render_gaussians, ssim, args.render_size)
    state = {n: p.detach().cpu() for n,p in model.gaussian_head.state_dict().items()
             if n.startswith(prefixes)}
    adapter_path = args.output / "vggt_gaussian_terminal_heads_adapter.pt"
    torch.save({"gaussian_head": state, "trainable_names": trainable_names, "steps": args.steps,
                "lr": args.lr, "seed": args.seed}, adapter_path)
    summary = {"method": "alternating phase-B: frozen VGGT backbone + terminal Gaussian heads",
               "checkpoint": checkpoint, "train_scenes": TRAIN, "validation_scenes": VAL,
               "trainable_names": trainable_names, "trainable_parameters": trainable_count,
               "steps": args.steps, "lr": args.lr, "render_size": args.render_size,
               "validation_before": before, "validation_after": after,
               "validation_psnr_delta": after["mean_psnr"]-before["mean_psnr"],
               "validation_ssim_delta": after["mean_ssim"]-before["mean_ssim"],
               "validation_l1_delta": after["mean_l1"]-before["mean_l1"],
               "elapsed_seconds": time.perf_counter()-started,
               "peak_allocated_gib": torch.cuda.max_memory_allocated(device)/1024**3,
               "adapter": str(adapter_path)}
    (args.output / "training_trace.json").write_text(json.dumps(trace, ensure_ascii=False, indent=2)+"\n")
    (args.output / "training_summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2)+"\n")
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__": main()
